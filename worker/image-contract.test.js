import assert from "node:assert/strict";
import { extractImageContract, enforceImageContract, imageContractInstructions } from "./image-contract.js";
const prompt="Crie um banner com 2 caminhões, coloque o texto \"BRYAN FRETES\" e meu WhatsApp 22992641530, formato story 9:16, sem pessoas.";
const c=extractImageContract(prompt);
assert.equal(c.counts[0].count,2);
assert(c.requestedText.includes("BRYAN FRETES"));
assert(c.requestedText.includes("22992641530"));
assert.equal(c.aspectRatio,"9:16");
assert(c.forbidden.some(s=>s.includes("pessoas")));
const plan=enforceImageContract({mode:"poster",aspectRatio:"1:1",requiresTextAccuracy:false,requestedText:["OUTRO TEXTO"]},prompt);
assert.equal(plan.aspectRatio,"9:16");
assert(plan.requestedText.includes("BRYAN FRETES"));
assert(plan.requestedText.includes("22992641530"));
assert(plan.requiresTextAccuracy);
const inst=imageContractInstructions(plan,prompt);
assert(inst.includes("2 × caminhões"));
assert(inst.includes("22992641530"));
assert.deepEqual(extractImageContract("Faça uma imagem bonita sem mudar o rosto").requestedText,[]);
const doNotInfer=extractImageContract("Faça uma foto de 2 pessoas em uma praça");
assert(doNotInfer.counts[0].count===2);
assert.equal(doNotInfer.requestedText.length,0);
console.log("image contract tests passed");
