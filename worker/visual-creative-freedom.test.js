import assert from "node:assert/strict";
import { VISUAL_CREATIVE_FREEDOM, isCreativeMontageRequest, applyCreativeMontagePlan } from "./visual-creative-freedom.js";
assert.match(VISUAL_CREATIVE_FREEDOM,/political figure/);
assert.match(VISUAL_CREATIVE_FREEDOM,/photographic composites/);
assert.match(VISUAL_CREATIVE_FREEDOM,/actual meeting/);
assert.equal(isCreativeMontageRequest("Me coloque ao lado do Bolsonaro nesta foto",true),true);
assert.equal(isCreativeMontageRequest("Faça uma fotomontagem minha com um político",true),true);
assert.equal(isCreativeMontageRequest("Adicione o presidente na minha foto ao meu lado",true),true);
assert.equal(isCreativeMontageRequest("Uma fotografia de um político discursando",false),false);
assert.equal(isCreativeMontageRequest("Desenhe um quadro político sem referência",true),false);
const plan=applyCreativeMontagePlan({mode:"strict_edit",editStrength:0.2,preservationLevel:"maximum",localized:true,successCriteria:[]}, "Coloque minha foto ao lado do Bolsonaro",true);
assert.equal(plan.mode,"strict_edit");
assert.equal(plan.editStrength,0.48);
assert.equal(plan.localized,false);
assert.equal(plan.requiresIdentityLock,true);
assert.equal(plan.preservationLevel,"high");
assert(plan.successCriteria.some(x=>x.includes("preservando")));
const unchanged={mode:"poster",editStrength:0.1};
assert.equal(applyCreativeMontagePlan(unchanged,"Cartaz sobre economia",true),unchanged);
console.log("creative image composites tests passed");
